/**
 * Wordmark + lockup generator: `deno task marks`.
 *
 * Outlines "Zentinel" in Unbounded (static 700 instance, fetched from the
 * Fontsource package on jsDelivr, OFL 1.1) into SVG paths, so the wordmark
 * renders identically everywhere with no font dependency. Writes:
 *
 *   marks/wordmark/zentinel-wordmark.svg            mono, fill=currentColor
 *   marks/wordmark/zentinel-wordmark-on-dark.svg    colour, orange-400
 *   marks/wordmark/zentinel-wordmark-on-light.svg   colour, orange-700
 *   marks/mark/zentinel-mark-disc-512.png           mascot disc, transparent corners (raster)
 *   marks/lockup/interim/zentinel-lockup-{dark,light}.svg   INTERIM: raster disc + vector wordmark
 *
 * The shisa itself only exists as a raster illustration (see
 * marks/PROVENANCE.md), so the lockups embed the disc as a PNG. When the
 * vector redraw lands, replace the <image> with its paths and add the
 * mono lockups. Needs network (font fetch) and ImageMagick (`magick`).
 */

// @ts-types="npm:@types/opentype.js@1.3.8"
import opentype from "opentype.js";
import { encodeBase64 } from "@std/encoding/base64";

const tokens = JSON.parse(await Deno.readTextFile("tokens.json"));
const C = tokens.color;

const FONT_URL =
  "https://cdn.jsdelivr.net/npm/@fontsource/unbounded@5.3.0/files/unbounded-latin-700-normal.woff";
const TEXT = "Zentinel";
const SIZE = 100; // px em; the viewBox is cropped to the ink, so this only sets precision

const buf = await (await fetch(FONT_URL)).arrayBuffer();
const font = opentype.parse(buf);
const path = font.getPath(TEXT, 0, 0, SIZE, { kerning: true });
const bb = path.getBoundingBox();
const w = +(bb.x2 - bb.x1).toFixed(2);
const h = +(bb.y2 - bb.y1).toFixed(2);
// Translate ink to the origin.
const shifted = font.getPath(TEXT, -bb.x1, -bb.y1, SIZE, { kerning: true });
const d = shifted.toPathData(2);

await Deno.mkdir("marks/wordmark", { recursive: true });
await Deno.mkdir("marks/lockup/interim", { recursive: true });
await Deno.mkdir("marks/mark", { recursive: true });

const credit = `<!-- Zentinel wordmark: "${TEXT}" in Unbounded 700 (SIL OFL 1.1), outlined by design/scripts/marks.ts. Generated; do not edit by hand. -->`;
const wordmark = (fill: string, title = "Zentinel") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" role="img" aria-label="${title}">\n${credit}\n<title>${title}</title>\n<path fill="${fill}" d="${d}"/>\n</svg>\n`;

await Deno.writeTextFile("marks/wordmark/zentinel-wordmark.svg", wordmark("currentColor"));
await Deno.writeTextFile("marks/wordmark/zentinel-wordmark-on-dark.svg", wordmark(C.orange["400"]));
await Deno.writeTextFile("marks/wordmark/zentinel-wordmark-on-light.svg", wordmark(C.orange["700"]));

// Mascot disc: the source illustration is a 1024px square with a vignette
// around a plum disc centred at (512, 512). Crop to the disc and drop the rest.
const disc = "marks/mark/zentinel-mark-disc-512.png";
const cmd = new Deno.Command("magick", {
  args: [
    "marks/source/zentinel-mascot-1024.png",
    "(", "+clone", "-alpha", "transparent", "-fill", "white", "-draw", "circle 512,512 512,142", ")",
    "-compose", "DstIn", "-composite", "-crop", "740x740+142+142", "+repage",
    "-resize", "512x512", "-strip", disc,
  ],
});
const res = await cmd.output();
if (!res.success) throw new Error(new TextDecoder().decode(res.stderr));
// Embed a 256px copy in the lockups: plenty for a lockup at header sizes.
const small = await new Deno.Command("magick", {
  args: [disc, "-resize", "256x256", "-strip", "-define", "png:compression-level=9", "png:-"],
}).output();
if (!small.success) throw new Error(new TextDecoder().decode(small.stderr));
const discB64 = encodeBase64(small.stdout);

// Horizontal lockup: disc at cap-height x 1.9, gap 0.32 x disc, wordmark
// baseline-centred on the disc.
const markH = h * 1.9;
const gap = markH * 0.32;
const W = +(markH + gap + w).toFixed(2);
const lockup = (textFill: string, label: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${W} ${markH.toFixed(2)}" role="img" aria-label="Zentinel">
<!-- INTERIM ${label} lockup: the shisa disc is an embedded raster (marks/mark/zentinel-mark-disc-512.png) until the vector redraw exists. Wordmark is outlined Unbounded 700 (OFL 1.1). Generated by design/scripts/marks.ts. -->
<title>Zentinel</title>
<image width="${markH.toFixed(2)}" height="${markH.toFixed(2)}" href="data:image/png;base64,${discB64}"/>
<path transform="translate(${(markH + gap).toFixed(2)} ${((markH - h) / 2).toFixed(2)})" fill="${textFill}" d="${d}"/>
</svg>
`;
await Deno.writeTextFile("marks/lockup/interim/zentinel-lockup-dark.svg", lockup(C.neutral["50"], "on-dark"));
await Deno.writeTextFile("marks/lockup/interim/zentinel-lockup-light.svg", lockup(C.neutral["950"], "on-light"));

console.log(`wordmark ${w}x${h}, lockup ${W}x${markH.toFixed(2)}; wrote marks/wordmark, marks/mark, marks/lockup`);
