/**
 * Zentinel design-token compiler: `deno task build` (or `deno task check`).
 *
 * Reads tokens.json, resolves {family.step} references, gates every declared
 * text/background pairing against WCAG 2.x contrast in both themes (exit 1 on
 * a violation), then writes dist/:
 *
 *   dist/css/tokens.css        custom properties: primitives, scales, dark + light roles, reduced motion
 *   dist/css/fonts.css         @font-face for the self-hosted fonts, served from /fonts/
 *   dist/css/frame.css         shared frame pieces: ::selection, :focus-visible, the physical button,
 *                              and the controls in components/controls.css (fields, checks, switches,
 *                              segmented controls, tabs, choice cards, copy buttons, menus, tooltips)
 *   dist/css/bridge.css        maps tanuki's names (--color-*, --ctp-*, --radius-*, --shadow-*) and the
 *                              site's legacy --color-* names onto --z-*, so any tanuki-based site follows
 *   dist/scss/_tokens.scss     the same as Sass: $z-* variables, theme maps + mixins, and the custom properties
 *   dist/scss/_fonts.scss      @font-face with a $z-font-path override
 *   dist/scss/_frame.scss      frame.css as a partial
 *   dist/tokens.resolved.json  every token with references resolved, per theme (for JS consumers)
 *   dist/contrast.json         every checked pairing with its ratio
 *   dist/preview/index.html    swatches, contrast, type, buttons and marks in both themes
 *
 * `--check` runs the contrast gate and writes nothing.
 */

import { contrast, over } from "./lib/color.ts";

type Dict = Record<string, unknown>;
const CHECK_ONLY = Deno.args.includes("--check");
const tokens = JSON.parse(await Deno.readTextFile("tokens.json"));
const THEMES = ["dark", "light"] as const;
type Theme = typeof THEMES[number];

const HEADER = "// AUTO-GENERATED by design/build.ts from tokens.json. Do not edit by hand.\n";
const CSS_HEADER = "/* AUTO-GENERATED by design/build.ts from tokens.json. Do not edit by hand. */\n";

// ── Resolution ───────────────────────────────────────────────────

const isMeta = (k: string) => k.startsWith("$");
const entries = (o: Dict) => Object.entries(o).filter(([k]) => !isMeta(k));

function lookup(path: string): string {
  const parts = path.split(".");
  // Colour primitives are addressed without the `color.` prefix: {orange.400}.
  let node: unknown = parts[0] in tokens.color ? tokens.color : tokens;
  for (const p of parts) {
    node = (node as Dict)?.[p];
    if (node === undefined) throw new Error(`unresolved token reference {${path}}`);
  }
  if (typeof node !== "string") throw new Error(`{${path}} is not a leaf`);
  return resolve(node);
}

function resolve(value: string): string {
  return value.replace(/\{([a-zA-Z0-9.-]+)\}/g, (_, p) => lookup(p));
}

const roles: Record<Theme, Record<string, string>> = { dark: {}, light: {} };
const roleRefs: Record<Theme, Record<string, string>> = { dark: {}, light: {} };
for (const t of THEMES) {
  for (const [k, v] of entries(tokens.semantic[t])) {
    roleRefs[t][k] = v as string;
    roles[t][k] = resolve(v as string);
  }
}
const darkKeys = Object.keys(roles.dark).sort().join();
if (darkKeys !== Object.keys(roles.light).sort().join()) {
  throw new Error("semantic.dark and semantic.light must define the same roles");
}

// Text-safe gradients: stops are semantic roles, resolved per theme.
type GradientText = { angle: string; stops: string[]; on: string[] };
const gradientText = entries(tokens.gradientText ?? {}) as [string, GradientText][];
for (const [name, g] of gradientText) {
  for (const r of [...g.stops, ...g.on]) {
    if (!(r in roles.dark)) throw new Error(`gradientText.${name} names unknown role ${r}`);
  }
}

/** The colour at fraction f (0..1) along evenly spaced stops, mixed in sRGB like a CSS gradient. */
function along(hexes: string[], f: number): string {
  const seg = Math.min(hexes.length - 2, Math.floor(f * (hexes.length - 1)));
  const local = f * (hexes.length - 1) - seg;
  return over(hexes[seg + 1], local, hexes[seg]);
}

const gradientCss = (t: Theme, g: GradientText) => {
  const n = g.stops.length - 1;
  return `linear-gradient(${g.angle}, ${g.stops.map((r, i) => `${roles[t][r]} ${Math.round((i / n) * 100)}%`).join(", ")})`;
};

// Channel variables: --z-<role>-rgb as space-separated "R G B", for
// rgb(var(--z-bg-rgb) / 0.8). One syntax for every --z-*-rgb, the same as
// the shadow-rgb role. (tanuki's legacy --color-*-rgb are comma-separated;
// the bridge emits those separately, see buildBridgeCss.)
const CHANNEL_ROLES = ["bg", "surface", "surface-raised", "text", "accent", "accent-2"];
const channels = (hex: string) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");

/** Per-theme values derived from the roles: channel triplets and text gradients. */
function themeExtras(t: Theme): [string, string][] {
  return [
    ...CHANNEL_ROLES.map((r) => [`${r}-rgb`, channels(roles[t][r])] as [string, string]),
    ...gradientText.map(([name, g]) => [`gradient-${name}`, gradientCss(t, g)] as [string, string]),
  ];
}

// ── Contrast gate ────────────────────────────────────────────────

const MIN = { text: 4.5, large: 3, ui: 3 } as Record<string, number>;
type Result = { theme: Theme; fg: string; bg: string; fgHex: string; bgHex: string; ratio: number; level: string; min: number; pass: boolean };
const results: Result[] = [];
const seen = new Set<string>();

for (const t of THEMES) {
  for (const rule of [...tokens.contrast.both, ...tokens.contrast[t]]) {
    for (const fg of rule.fg as string[]) {
      for (const bg of rule.bg as string[]) {
        const key = `${t}|${fg}|${bg}|${rule.level}`;
        if (seen.has(key)) continue;
        seen.add(key);
        const fgHex = roles[t][fg], bgHex = roles[t][bg];
        if (!fgHex || !bgHex) throw new Error(`contrast rule names unknown role: ${fg} on ${bg}`);
        const ratio = contrast(fgHex, bgHex);
        const min = MIN[rule.level];
        if (min === undefined) throw new Error(`unknown contrast level ${rule.level}`);
        results.push({ theme: t, fg, bg, fgHex, bgHex, ratio: +ratio.toFixed(2), level: rule.level, min, pass: ratio >= min });
      }
    }
  }
  // Every text gradient: each stop and the colour between them, on each ground it may sit on.
  for (const [name, g] of gradientText) {
    const hexes = g.stops.map((r) => roles[t][r]);
    const samples: [string, string][] = [
      ...g.stops.map((r) => [r, roles[t][r]] as [string, string]),
      ...[0.25, 0.5, 0.75].map((f) => [`gradient-${name}@${f * 100}%`, along(hexes, f)] as [string, string]),
    ];
    for (const bg of g.on) {
      for (const [fg, fgHex] of samples) {
        const key = `${t}|${fg}|${bg}|text`;
        if (seen.has(key)) continue;
        seen.add(key);
        const ratio = contrast(fgHex, roles[t][bg]);
        results.push({ theme: t, fg, bg, fgHex, bgHex: roles[t][bg], ratio: +ratio.toFixed(2), level: "text", min: MIN.text, pass: ratio >= MIN.text });
      }
    }
  }
}

const failures = results.filter((r) => !r.pass);
for (const t of THEMES) {
  const rs = results.filter((r) => r.theme === t);
  const worst = rs.reduce((a, b) => (b.ratio / b.min < a.ratio / a.min ? b : a));
  console.log(
    `contrast ${t}: ${rs.length} pairings, ${rs.filter((r) => r.pass).length} pass; tightest ${worst.fg} on ${worst.bg} ${worst.ratio}:1 (needs ${worst.min})`,
  );
}
if (failures.length) {
  console.error("\nContrast violations:");
  for (const f of failures) {
    console.error(`  [${f.theme}] ${f.fg} ${f.fgHex} on ${f.bg} ${f.bgHex}: ${f.ratio}:1 < ${f.min}:1 (${f.level})`);
  }
  Deno.exit(1);
}
if (CHECK_ONLY) Deno.exit(0);

// ── Flat token lists ─────────────────────────────────────────────

/** Theme-independent custom properties, as [name, value] without the leading `--z-`. */
function staticVars(): [string, string][] {
  const out: [string, string][] = [];
  for (const [fam, ramp] of entries(tokens.color)) {
    for (const [step, hex] of entries(ramp as Dict)) out.push([`${fam}-${step}`, hex as string]);
  }
  for (const [k, v] of entries(tokens.font)) out.push([`font-${k}`, v as string]);
  for (const [k, v] of entries(tokens.fontSize)) out.push([`size-${k}`, v as string]);
  for (const [k, v] of entries(tokens.fontWeight)) out.push([`weight-${k}`, v as string]);
  for (const [k, v] of entries(tokens.lineHeight)) out.push([`leading-${k}`, v as string]);
  for (const [k, v] of entries(tokens.letterSpacing)) out.push([`tracking-${k}`, v as string]);
  for (const [k, v] of entries(tokens.space)) out.push([`space-${k}`, v as string]);
  for (const [k, v] of entries(tokens.layout)) out.push([`layout-${k}`, v as string]);
  for (const [k, v] of entries(tokens.radius)) out.push([`radius-${k}`, v as string]);
  for (const [k, v] of entries(tokens.shadow)) out.push([`shadow-${k}`, v as string]);
  for (const [k, v] of entries(tokens.button)) out.push([`button-${k}`, resolve(v as string)]);
  for (const [k, v] of entries(tokens.control)) out.push([`control-${k}`, resolve(v as string)]);
  for (const [k, v] of entries(tokens.motion)) out.push([k === "lift" ? "lift" : k, v as string]);
  for (const [k, v] of entries(tokens.gradient)) out.push([`gradient-${k}`, resolve(v as string)]);
  return out;
}

// Comma-separated triplet, only for tanuki's legacy --color-*-rgb (it writes
// rgba(var(--color-bg-rgb), a), which a space-separated value would break).
const rgbTriplet = (hex: string) =>
  [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(", ");

function themeVars(t: Theme): [string, string][] {
  return [...Object.entries(roles[t]), ...themeExtras(t)];
}

const reduced = entries(tokens.reducedMotion) as [string, string][];

// ── CSS ──────────────────────────────────────────────────────────

const decl = (pairs: [string, string][], indent = "  ") =>
  pairs.map(([k, v]) => `${indent}--z-${k}: ${v};`).join("\n");

function themeBlock(t: Theme, indent = "  "): string {
  return `${decl(themeVars(t), indent)}\n${indent}color-scheme: ${t};`;
}

function buildTokensCss(): string {
  return `${CSS_HEADER}
:root {
${decl(staticVars())}
}

/* Dark is the default ground; light via [data-theme="light"] or the OS
   preference when the page sets no data-theme. */
:root,
[data-theme="dark"] {
${themeBlock("dark")}
}

[data-theme="light"] {
${themeBlock("light")}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
${themeBlock("light", "    ")}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
${decl(reduced, "    ")}
  }
}
`;
}

function fontFaces(base: string): string {
  const out: string[] = [];
  for (const face of tokens.fontFace) {
    for (const [subset, file] of Object.entries(face.files as Record<string, string>)) {
      out.push(`@font-face {
  font-family: '${face.family}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url('${base}/${file}') format('woff2');
  unicode-range: ${tokens.unicodeRange[subset]};
}`);
    }
  }
  return out.join("\n\n");
}

