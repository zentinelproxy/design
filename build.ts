// ── SCSS ─────────────────────────────────────────────────────────

function buildTokensScss(css: string): string {
  // Plain values go in as-is; anything with var(), commas or functions is
  // unquoted so Sass (grass in Zola, dart-sass elsewhere) passes it through.
  const scssVal = (val: string) =>
    /^(#[0-9a-f]{6}|[0-9.]+(px|rem|em|ms|ch|%)?|-?[0-9.]+em)$/i.test(val) ? val : `unquote("${val}")`;
  const v = staticVars().map(([k, val]) => `$z-${k}: ${scssVal(val)};`).join("\n");
  const themed = THEMES.map((t) =>
    `${Object.entries(roles[t]).map(([k, val]) => `$z-${t}-${k}: ${val};`).join("\n")}\n\n$z-theme-${t}: (\n${
      Object.entries(roles[t]).map(([k, val]) => `  "${k}": ${/^#/.test(val) ? val : `"${val}"`},`).join("\n")
    }\n);`
  ).join("\n\n");
  return `${HEADER}
// Sass variables mirror the custom properties. Prefer var(--z-*) in rules so
// the theme switch works; use $z-* where Sass needs a literal (color.adjust, media queries).

${v}

${themed}

// Emit one theme's roles as custom properties: @include z-theme(light);
@mixin z-theme($theme) {
  $map: $z-theme-dark;
  @if $theme == light {
    $map: $z-theme-light;
  }
  @each $name, $value in $map {
    --z-#{$name}: #{$value};
  }
  color-scheme: $theme;
}

// The custom properties themselves (same output as dist/css/tokens.css).
${css.replace(CSS_HEADER, "")}`;
}

// ── Preview ──────────────────────────────────────────────────────

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function swatchRow(fam: string, ramp: Dict): string {
  const cells = entries(ramp).map(([step, hex]) => {
    const h = hex as string;
    const onDark = contrast(h, roles.dark.bg), onLight = contrast(h, roles.light.bg);
    const ink = contrast(h, "#000000") > contrast(h, "#ffffff") ? "#000" : "#fff";
    return `<div class="sw" style="background:${h};color:${ink}"><b>${step}</b><code>${h}</code><small>${onDark.toFixed(1)} dk · ${onLight.toFixed(1)} lt</small></div>`;
  }).join("");
  return `<div class="ramp"><h3>${fam}</h3><div class="sws">${cells}</div></div>`;
}

function rolesTable(t: Theme): string {
  return `<div class="roles">${
    Object.entries(roles[t]).filter(([k]) => k !== "shadow-rgb").map(([k, hex]) =>
      `<div class="role"><span class="chip" style="background:${hex}"></span><span><b>${k}</b><br><code>${hex}</code> <small>${esc(roleRefs[t][k])}</small></span></div>`
    ).join("")
  }</div>`;
}

function contrastTable(t: Theme): string {
  const rows = results.filter((r) => r.theme === t).map((r) =>
    `<tr><td><span class="sample" style="color:${r.fgHex};background:${r.bgHex}">Aa</span></td><td>${r.fg}<br><code>${r.fgHex}</code></td><td>${r.bg}<br><code>${r.bgHex}</code></td><td class="num">${r.ratio.toFixed(2)}</td><td>${r.level} ≥ ${r.min}</td><td>${r.pass ? "pass" : "FAIL"}</td></tr>`
  ).join("");
  return `<table class="ct"><thead><tr><th></th><th>Foreground</th><th>Background</th><th>Ratio</th><th>Needs</th><th></th></tr></thead><tbody>${rows}</tbody></table>`;
}

function typeScale(): string {
  const sizes = entries(tokens.fontSize).reverse();
  return sizes.map(([k, v]) =>
    `<div class="ts"><small>${k} · ${v}</small><span style="font-size:${v}" class="${["6xl", "5xl", "4xl", "3xl", "2xl"].includes(k) ? "disp" : ""}">${["6xl", "5xl", "4xl", "3xl", "2xl"].includes(k) ? "Guardian of the free web" : "Explicit configuration over hidden defaults; agents fail in isolation."}</span></div>`
  ).join("");
}

function panel(t: Theme, body: string): string {
  return `<div class="panel" data-theme="${t}"><p class="tag">${t}</p>${body}</div>`;
}

function pair(body: (t: Theme) => string): string {
  return `<div class="pair">${panel("dark", body("dark"))}${panel("light", body("light"))}</div>`;
}

